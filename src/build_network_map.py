#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Build one static OSM plate covering the central 3-node network.

Reads the network bundles in data/config/anchor_bundles.json, takes the union
of their member anchors, stitches existing z14 offline tiles, and writes:
  src/assets/map-network-central.png
  src/map-network.js   (window.MAP_ASSETS["network-central"] = {...})

Run after src/build_tiles.py so the z14 tiles exist:
  python src/build_network_map.py
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

from PIL import Image

SRC = Path(__file__).resolve().parent
ROOT = SRC.parent
DATA = ROOT / "data"
sys.path.insert(0, str(SRC))
from build_data import bd09_to_wgs84  # noqa: E402
TILES = SRC / "assets" / "tiles"
OUT_IMG = SRC / "assets" / "map-network-central.jpg"
OUT_JS = SRC / "map-network.js"
KEY = "network-central"
ZOOM = 14
TILE = 256
PAD_M = 1200


def lon_to_px(lon: float, z: int) -> float:
    return (lon + 180.0) / 360.0 * (2 ** z) * TILE


def lat_to_py(lat: float, z: int) -> float:
    s = math.sin(math.radians(lat))
    return (0.5 - math.log((1 + s) / (1 - s)) / (4 * math.pi)) * (2 ** z) * TILE


def px_to_lon(px: float, z: int) -> float:
    return px / ((2 ** z) * TILE) * 360.0 - 180.0


def py_to_lat(py: float, z: int) -> float:
    n = math.pi - 2.0 * math.pi * py / ((2 ** z) * TILE)
    return math.degrees(math.atan(math.sinh(n)))


def main() -> int:
    anchors = {a["anchorId"]: a for a in (json.loads((DATA / "config" / "anchors.json").read_text(encoding="utf-8")).get("anchors") or [])}
    bundles = json.loads((DATA / "config" / "anchor_bundles.json").read_text(encoding="utf-8")).get("bundles") or []
    members = []
    for b in bundles:
        if b.get("mapAssetKey") != KEY:
            continue
        for m in b.get("members") or []:
            a = anchors.get(m.get("anchorId"))
            if a and a.get("lng") and a.get("lat"):
                wlng, wlat = bd09_to_wgs84(float(a["lng"]), float(a["lat"]))
                members.append({"lng": wlng, "lat": wlat})
    if not members:
        raise SystemExit("no members found for mapAssetKey=" + KEY)

    lngs = [float(a["lng"]) for a in members]
    lats = [float(a["lat"]) for a in members]
    coslat = math.cos(math.radians(sum(lats) / len(lats)))
    min_lng = min(lngs) - PAD_M / (111000.0 * max(0.2, coslat))
    max_lng = max(lngs) + PAD_M / (111000.0 * max(0.2, coslat))
    min_lat = min(lats) - PAD_M / 111000.0
    max_lat = max(lats) + PAD_M / 111000.0

    x0 = int(math.floor(lon_to_px(min_lng, ZOOM) / TILE))
    x1 = int(math.floor(lon_to_px(max_lng, ZOOM) / TILE))
    y0 = int(math.floor(lat_to_py(max_lat, ZOOM) / TILE))
    y1 = int(math.floor(lat_to_py(min_lat, ZOOM) / TILE))
    w, h = (x1 - x0 + 1) * TILE, (y1 - y0 + 1) * TILE

    canvas = Image.new("RGB", (w, h), (250, 248, 242))
    missing = []
    for x in range(x0, x1 + 1):
        for y in range(y0, y1 + 1):
            p = TILES / str(ZOOM) / str(x) / f"{y}.png"
            if not (p.exists() and p.stat().st_size > 1000):
                missing.append((x, y))
                continue
            canvas.paste(Image.open(p).convert("RGB"), ((x - x0) * TILE, (y - y0) * TILE))
    if missing:
        print(f"[warn] {len(missing)} z{ZOOM} tiles missing; run src/build_tiles.py first: {missing[:6]}")
    OUT_IMG.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(OUT_IMG, quality=82, optimize=True)

    meta = {
        "file": "assets/map-network-central.jpg?v=20261121b",
        "width": w,
        "height": h,
        "zoom": ZOOM,
        "tiles": (x1 - x0 + 1) * (y1 - y0 + 1),
        "anchor": "上海中心三网点",
        "radius": 14000,
        "attribution": "© OpenStreetMap contributors (ODbL)",
        "minLng": round(px_to_lon(x0 * TILE, ZOOM), 8),
        "maxLng": round(px_to_lon((x1 + 1) * TILE, ZOOM), 8),
        "minLat": round(py_to_lat((y1 + 1) * TILE, ZOOM), 8),
        "maxLat": round(py_to_lat(y0 * TILE, ZOOM), 8),
    }
    OUT_JS.write_text(
        "/* generated by src/build_network_map.py — central 3-node OSM plate, © OpenStreetMap contributors (ODbL) */\n"
        "window.MAP_ASSETS = window.MAP_ASSETS || {};\n"
        "window.MAP_ASSETS[\"" + KEY + "\"] = " + json.dumps(meta, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"[ok] {OUT_IMG} ({w}x{h}, {OUT_IMG.stat().st_size/1024:.0f} KB)")
    print(f"[ok] {OUT_JS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
