#!/usr/bin/env node
/* Build a compact sample plan for the three design directions (real data, no Lorem). */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const SRC = __dirname;
const ROOT = path.join(SRC, "..");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, "data.js"), "utf8"), ctx, { filename: "data.js" });
const data = ctx.window.APP_DATA;
const Engine = require(path.join(ROOT, "engine.js"));

const brief = {
  anchor: "上海美华妇儿医院",
  radius: 3000,
  budget: 2000000,
  weeks: 6,
  media: { bus: true, metro: true },
  startDate: "2027-04-01"
};
const plan = Engine.selectPlan(data, brief);
const cov = data.coverage[brief.anchor]["3000"];
const selectedBus = new Set(plan.items.filter((x) => x.media === "bus").map((x) => x.line));
const selectedMetro = new Set(plan.items.filter((x) => x.media === "metro").map((x) => x.station));

const busPoints = cov.list.filter((r) => r.mediaType === "bus").map((r) => {
  const alias = data.aliases[r.lineName] || {};
  return {
    name: r.lineName,
    line: alias.inventoryName || r.lineName,
    distance: Math.round(r.minDistance),
    lng: r.pointLng,
    lat: r.pointLat,
    selected: !!alias.inventoryName && selectedBus.has(alias.inventoryName)
  };
});
const metroPoints = cov.list.filter((r) => r.mediaType === "metro").map((r) => ({
  station: r.pointName,
  line: r.lineName,
  distance: Math.round(r.minDistance),
  lng: r.pointLng,
  lat: r.pointLat,
  selected: selectedMetro.has(r.pointName)
}));

const sample = {
  meta: {
    fetchedAt: data.meta.inventoryFetchedAt,
    range: data.meta.range,
    busRows: data.meta.counts.busRows,
    busFree: data.meta.counts.busFree,
    metroRows: data.meta.counts.metroRows,
    metroFree: data.meta.counts.metroFree
  },
  anchors: data.anchors.map((a) => ({ name: a.name, short: a.short, type: a.type, center: a.center })),
  activeAnchor: brief.anchor,
  radius: brief.radius,
  center: cov.center,
  plan: {
    items: plan.items,
    summary: plan.summary,
    quote: plan.quote,
    stats: plan.stats,
    schedule: plan.schedule,
    warnings: plan.warnings
  },
  points: { bus: busPoints, metro: metroPoints }
};

const out = "/* generated by src/design/build_sample.js — real 200万/6周 plan for design comps */\n" +
  "window.SAMPLE = " + JSON.stringify(sample, null, 2) + ";\n";
fs.writeFileSync(path.join(SRC, "sample-data.js"), out, "utf8");
console.log(`sample-data.js ${(Buffer.byteLength(out) / 1024).toFixed(1)} KB; plan rows ${plan.items.length}; bus ${plan.summary.busCount}; metro ${plan.summary.metroCount}; net ${(plan.quote.net / 10000).toFixed(1)}万`);
