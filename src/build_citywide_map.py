#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Build the citywide OSM plate for the Disney 4-hub plan.

Reads the `citywide` bundle's explicit mapBounds (WGS84), stitches the z13
offline tiles, and writes:
  src/assets/map-network-citywide.jpg
  src/map-citywide.js   (window.MAP_ASSETS["network-citywide"] = {...})

Run after src/build_tiles.py:
  python src/build_citywide_map.py
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

from PIL import Image

SRC = Path(__file__).resolve().parent
ROOT = SRC.parent
DATA = ROOT / "data"
TILES = SRC / "assets" / "tiles"
OUT_IMG = SRC / "assets" / "map-network-citywide.jpg"
OUT_JS = SRC / "map-citywide.js"
KEY = "network-citywide"
ZOOM = 13
TILE = 256


def lon_to_px(lon: float, z: int) -> float:
    return (lon + 180.0) / 360.0 * (2 ** z) * TILE


def lat_to_py(lat: float, z: int) -> float:
    s = math.sin(math.radians(lat))
    return (0.5 - math.log((1 + s) / (1 - s)) / (4 * math.pi)) * (2 ** z) * TILE


def px_to_lon(px: float, z: int) -> float:
    return px / ((2 ** z) * TILE) * 360.0 - 180.0


def py_to_lat(py: float, z: int) -> float:
    n = math.pi - 2.0 * math.pi * py / ((2 ** z) * TILE)
    return math.degrees(math.atan(math.sinh(n)))


def find_bounds() -> dict:
    bundles = json.loads((DATA / "config" / "anchor_bundles.json").read_text(encoding="utf-8")).get("bundles") or []
    for b in bundles:
        if b.get("bundleId") == "disney-city":
            mb = b.get("mapBounds") or {}
            if mb.get("minLng") is not None:
                return {k: float(mb[k]) for k in ("minLng", "minLat", "maxLng", "maxLat")}
    raise SystemExit("disney-city bundle with mapBounds not found")


def main() -> int:
    b = find_bounds()
    min_lng, min_lat, max_lng, max_lat = b["minLng"], b["minLat"], b["maxLng"], b["maxLat"]
    x0 = int(math.floor(lon_to_px(min_lng, ZOOM) / TILE))
    x1 = int(math.floor(lon_to_px(max_lng, ZOOM) / TILE))
    y0 = int(math.floor(lat_to_py(max_lat, ZOOM) / TILE))
    y1 = int(math.floor(lat_to_py(min_lat, ZOOM) / TILE))
    w, h = (x1 - x0 + 1) * TILE, (y1 - y0 + 1) * TILE

    canvas = Image.new("RGB", (w, h), (250, 248, 242))
    missing = []
    for x in range(x0, x1 + 1):
        for y in range(y0, y1 + 1):
            p = TILES / str(ZOOM) / str(x) / f"{y}.png"
            if not (p.exists() and p.stat().st_size > 1000):
                missing.append((x, y))
                continue
            canvas.paste(Image.open(p).convert("RGB"), ((x - x0) * TILE, (y - y0) * TILE))
    if missing:
        print(f"[warn] {len(missing)} z{ZOOM} tiles missing; run src/build_tiles.py first: {missing[:6]}")
    OUT_IMG.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(OUT_IMG, quality=82, optimize=True)

    meta = {
        "file": "assets/map-network-citywide.jpg?v=20261121a",
        "width": w,
        "height": h,
        "zoom": ZOOM,
        "tiles": (x1 - x0 + 1) * (y1 - y0 + 1),
        "anchor": "迪士尼全城 4 枢纽 + 24 站",
        "radius": 22000,
        "attribution": "© OpenStreetMap contributors (ODbL)",
        "minLng": round(px_to_lon(x0 * TILE, ZOOM), 8),
        "maxLng": round(px_to_lon((x1 + 1) * TILE, ZOOM), 8),
        "minLat": round(py_to_lat((y1 + 1) * TILE, ZOOM), 8),
        "maxLat": round(py_to_lat(y0 * TILE, ZOOM), 8),
    }
    OUT_JS.write_text(
        "/* generated by src/build_citywide_map.py — citywide OSM plate, © OpenStreetMap contributors (ODbL) */\n"
        "window.MAP_ASSETS = window.MAP_ASSETS || {};\n"
        "window.MAP_ASSETS[\"" + KEY + "\"] = " + json.dumps(meta, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"[ok] {OUT_IMG} ({w}x{h}, {OUT_IMG.stat().st_size/1024:.0f} KB)")
    print(f"[ok] {OUT_JS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
